#!/usr/bin/env python3
"""
Stage 2 for policy distillation.

Train a memory-free student from datasets generated by the teacher collection
script. The default student is SimpleAgent; a larger distillation-only MLP can
be selected without modifying repository model definitions.
"""

import argparse
import json
import math
import random
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim

from models import SimpleAgent


LOG_STD_MAX = 2
LOG_STD_MIN = -20


class DistillMLPAgent(nn.Module):
    def __init__(
        self,
        obs_dim: int,
        act_dim: int,
        hidden_dim: int = 512,
        num_layers: int = 3,
        activation: str = "relu",
        layer_norm: bool = False,
    ):
        super().__init__()
        if num_layers < 1:
            raise ValueError(f"num_layers must be at least 1, got {num_layers}")

        self.obs_dim = int(obs_dim)
        self.act_dim = int(act_dim)
        self.hidden_dim = int(hidden_dim)
        self.num_layers = int(num_layers)
        self.activation = activation
        self.layer_norm = bool(layer_norm)

        if activation == "relu":
            activation_cls = nn.ReLU
        elif activation == "gelu":
            activation_cls = nn.GELU
        elif activation == "tanh":
            activation_cls = nn.Tanh
        else:
            raise ValueError(f"Unsupported activation: {activation}")

        layers = []
        in_dim = self.obs_dim
        for _ in range(self.num_layers):
            layers.append(nn.Linear(in_dim, self.hidden_dim))
            if self.layer_norm:
                layers.append(nn.LayerNorm(self.hidden_dim))
            layers.append(activation_cls())
            in_dim = self.hidden_dim
        self.backbone = nn.Sequential(*layers)
        self.fc_mean = nn.Linear(self.hidden_dim, self.act_dim)
        self.fc_logstd = nn.Linear(self.hidden_dim, self.act_dim)

    def forward(self, x: torch.Tensor):
        h = self.backbone(x)
        return self.fc_mean(h), self.fc_logstd(h)


def safe_torch_load(path: Path, map_location):
    try:
        return torch.load(path, map_location=map_location, weights_only=False)
    except TypeError:
        return torch.load(path, map_location=map_location)


def sac_log_std(raw_log_std: torch.Tensor) -> torch.Tensor:
    log_std = torch.tanh(raw_log_std)
    return LOG_STD_MIN + 0.5 * (LOG_STD_MAX - LOG_STD_MIN) * (log_std + 1)


def gaussian_kl(
    teacher_mean: torch.Tensor,
    teacher_log_std: torch.Tensor,
    student_mean: torch.Tensor,
    student_log_std: torch.Tensor,
    temperature: float,
) -> torch.Tensor:
    if temperature <= 0:
        raise ValueError(f"temperature must be positive, got {temperature}")

    log_temp = math.log(temperature)
    teacher_log_std = teacher_log_std + log_temp
    student_log_std = student_log_std + log_temp

    teacher_var = torch.exp(2.0 * teacher_log_std)
    student_var = torch.exp(2.0 * student_log_std).clamp_min(1e-12)

    kl_per_dim = (
        student_log_std
        - teacher_log_std
        + (teacher_var + (teacher_mean - student_mean).pow(2)) / (2.0 * student_var)
        - 0.5
    )
    return kl_per_dim.sum(dim=-1).mean()


def policy_kl(
    teacher_mean: torch.Tensor,
    teacher_log_std: torch.Tensor,
    student_mean: torch.Tensor,
    student_log_std: torch.Tensor,
    temperature: float,
    direction: str,
) -> torch.Tensor:
    if direction == "forward":
        return gaussian_kl(
            teacher_mean=teacher_mean,
            teacher_log_std=teacher_log_std,
            student_mean=student_mean,
            student_log_std=student_log_std,
            temperature=temperature,
        )
    if direction == "reverse":
        return gaussian_kl(
            teacher_mean=student_mean,
            teacher_log_std=student_log_std,
            student_mean=teacher_mean,
            student_log_std=teacher_log_std,
            temperature=temperature,
        )
    raise ValueError(f"Unknown KL direction: {direction}")


def forward_student(student: nn.Module, obs: torch.Tensor):
    mean, raw_log_std = student(obs)
    return mean, sac_log_std(raw_log_std)


def read_manifest(dataset_dir: Path) -> Dict:
    manifest_path = dataset_dir / "manifest.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"Cannot find manifest: {manifest_path}")
    with open(manifest_path, "r", encoding="utf-8") as f:
        return json.load(f)


def load_datasets(dataset_dir: Path, task_ids: Sequence[int]) -> List[Dict]:
    manifest = read_manifest(dataset_dir)
    wanted = set(int(task_id) for task_id in task_ids)
    datasets = []

    for entry in manifest["tasks"]:
        task_id = int(entry["task_id"])
        if task_id not in wanted:
            continue
        path = dataset_dir / entry["path"]
        data = safe_torch_load(path, map_location="cpu")
        required = ["observations", "teacher_means", "teacher_log_stds"]
        missing = [key for key in required if key not in data]
        if missing:
            raise KeyError(f"{path} is missing keys: {missing}")
        datasets.append(data)

    if not datasets:
        raise ValueError(f"No datasets selected from {dataset_dir} for tasks {sorted(wanted)}")
    return datasets


def check_dataset_shapes(datasets: Sequence[Dict]) -> Tuple[int, int]:
    obs_dim = int(datasets[0]["observations"].shape[-1])
    act_dim = int(datasets[0]["teacher_means"].shape[-1])

    for data in datasets:
        observations = data["observations"]
        teacher_means = data["teacher_means"]
        teacher_log_stds = data["teacher_log_stds"]
        if observations.dim() != 2:
            raise ValueError(f"observations should be 2D, got {tuple(observations.shape)}")
        if teacher_means.shape != teacher_log_stds.shape:
            raise ValueError(
                f"teacher_means and teacher_log_stds shape mismatch: "
                f"{tuple(teacher_means.shape)} vs {tuple(teacher_log_stds.shape)}"
            )
        if observations.size(0) != teacher_means.size(0):
            raise ValueError(
                f"sample count mismatch for task {data.get('task_id')}: "
                f"{observations.size(0)} obs vs {teacher_means.size(0)} labels"
            )
        if observations.size(-1) != obs_dim or teacher_means.size(-1) != act_dim:
            raise ValueError("All datasets must share observation/action dimensions.")

    return obs_dim, act_dim


def sample_batch(data: Dict, batch_size: int, device: torch.device):
    n = int(data["observations"].size(0))
    idx = torch.randint(0, n, (batch_size,))
    obs = data["observations"][idx].to(device=device, dtype=torch.float32)
    means = data["teacher_means"][idx].to(device=device, dtype=torch.float32)
    log_stds = data["teacher_log_stds"][idx].to(device=device, dtype=torch.float32)
    actions = None
    if "teacher_actions" in data:
        actions = data["teacher_actions"][idx].to(device=device, dtype=torch.float32)
    return obs, means, log_stds, actions


def choose_dataset(datasets: Sequence[Dict], step: int, balanced: bool):
    if balanced:
        return datasets[(step - 1) % len(datasets)]
    return random.choice(datasets)


def student_checkpoint(student: nn.Module, meta: Dict) -> Dict:
    student_meta = meta["student"]
    return {
        "checkpoint_type": "distilled_student",
        "student": student_meta,
        "obs_dim": int(meta["obs_dim"]),
        "act_dim": int(meta["act_dim"]),
        "state_dict": student.state_dict(),
        "meta": meta,
    }


def save_student(student: nn.Module, save_dir: Path, meta: Dict) -> None:
    save_dir.mkdir(parents=True, exist_ok=True)
    torch.save(student_checkpoint(student, meta), save_dir / "model.pt")
    with open(save_dir / "distill_meta.json", "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2, sort_keys=True)


def build_student(args, obs_dim: int, act_dim: int, device: torch.device) -> nn.Module:
    if args.student_model_type == "simple":
        return SimpleAgent(obs_dim=obs_dim, act_dim=act_dim).to(device)
    if args.student_model_type == "mlp":
        return DistillMLPAgent(
            obs_dim=obs_dim,
            act_dim=act_dim,
            hidden_dim=args.hidden_dim,
            num_layers=args.num_layers,
            activation=args.activation,
            layer_norm=args.layer_norm,
        ).to(device)
    raise ValueError(f"Unsupported student model type: {args.student_model_type}")


def build_meta(args, datasets: Sequence[Dict], obs_dim: int, act_dim: int, step: int, best_loss: float):
    return {
        "student": {
            "model_type": args.student_model_type,
            "hidden_dim": args.hidden_dim if args.student_model_type == "mlp" else None,
            "num_layers": args.num_layers if args.student_model_type == "mlp" else None,
            "activation": args.activation if args.student_model_type == "mlp" else None,
            "layer_norm": args.layer_norm if args.student_model_type == "mlp" else None,
        },
        "obs_dim": obs_dim,
        "act_dim": act_dim,
        "step": step,
        "best_loss": best_loss,
        "dataset_dir": args.dataset_dir,
        "loss": {
            "type": "gaussian_policy_kl",
            "direction": args.kl_direction,
            "temperature": args.temperature,
            "mean_mse_coef": args.mean_mse_coef,
            "action_mse_coef": args.action_mse_coef,
        },
        "datasets": [
            {
                "task_id": int(data["task_id"]),
                "task_name": data.get("task_name"),
                "num_samples": int(data["observations"].size(0)),
                "rollout_success_rate": float(data.get("success_rate", np.nan)),
                "rollout_average_return": float(data.get("average_return", np.nan)),
            }
            for data in datasets
        ],
        "args": vars(args),
    }


def train(args):
    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)
    torch.backends.cudnn.deterministic = args.torch_deterministic

    device = torch.device(args.device)
    dataset_dir = Path(args.dataset_dir).expanduser()
    datasets = load_datasets(dataset_dir, args.tasks)
    obs_dim, act_dim = check_dataset_shapes(datasets)

    student = build_student(args, obs_dim=obs_dim, act_dim=act_dim, device=device)
    optimizer = optim.Adam(student.parameters(), lr=args.lr, weight_decay=args.weight_decay)

    print("*** Training distilled student from fixed datasets ***")
    print(f"dataset_dir: {dataset_dir}")
    print(f"device: {device}")
    print(f"student: {student.__class__.__name__}(obs_dim={obs_dim}, act_dim={act_dim})")
    if args.student_model_type == "mlp":
        print(
            f"student_config: hidden_dim={args.hidden_dim}, num_layers={args.num_layers}, "
            f"activation={args.activation}, layer_norm={args.layer_norm}"
        )
    for data in datasets:
        print(
            f"task {int(data['task_id']):02d}: "
            f"samples={int(data['observations'].size(0))}, "
            f"rollout_success={float(data.get('success_rate', np.nan)):.4f}"
        )

    running_loss = 0.0
    running_kl = 0.0
    running_mse = 0.0
    running_action_mse = 0.0
    best_loss = float("inf")
    student.train()

    for step in range(1, args.steps + 1):
        data = choose_dataset(datasets, step=step, balanced=args.balanced_tasks)
        obs, teacher_mean, teacher_log_std, teacher_action = sample_batch(data, args.batch_size, device)
        student_mean, student_log_std = forward_student(student, obs)

        kl_loss = policy_kl(
            teacher_mean=teacher_mean,
            teacher_log_std=teacher_log_std,
            student_mean=student_mean,
            student_log_std=student_log_std,
            temperature=args.temperature,
            direction=args.kl_direction,
        )
        mse_loss = (student_mean - teacher_mean).pow(2).mean()
        action_mse_loss = torch.zeros((), device=device)
        if teacher_action is not None:
            student_action = torch.tanh(student_mean)
            action_mse_loss = (student_action - teacher_action).pow(2).mean()
        loss = (
            kl_loss
            + args.mean_mse_coef * mse_loss
            + args.action_mse_coef * action_mse_loss
        )

        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        if args.max_grad_norm > 0:
            nn.utils.clip_grad_norm_(student.parameters(), args.max_grad_norm)
        optimizer.step()

        running_loss += float(loss.item())
        running_kl += float(kl_loss.item())
        running_mse += float(mse_loss.item())
        running_action_mse += float(action_mse_loss.item())
        best_loss = min(best_loss, float(loss.item()))

        if step == 1 or step % args.log_every == 0:
            denom = 1 if step == 1 else args.log_every
            print(
                f"step {step:06d}/{args.steps}: "
                f"loss={running_loss / denom:.6f}, "
                f"kl={running_kl / denom:.6f}, "
                f"mean_mse={running_mse / denom:.6f}, "
                f"action_mse={running_action_mse / denom:.6f}"
            )
            running_loss = 0.0
            running_kl = 0.0
            running_mse = 0.0
            running_action_mse = 0.0

        if args.save_every > 0 and step % args.save_every == 0:
            checkpoint_dir = Path(args.save_dir).expanduser() / f"checkpoint_step_{step}"
            save_student(
                student,
                checkpoint_dir,
                build_meta(args, datasets, obs_dim, act_dim, step, best_loss),
            )
            print(f"saved checkpoint: {checkpoint_dir / 'model.pt'}")

    save_dir = Path(args.save_dir).expanduser()
    save_student(
        student,
        save_dir,
        build_meta(args, datasets, obs_dim, act_dim, args.steps, best_loss),
    )
    print(f"saved student model: {save_dir / 'model.pt'}")
    print(f"saved metadata: {save_dir / 'distill_meta.json'}")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Train a memory-free student from fixed teacher rollout distillation datasets."
    )
    parser.add_argument("--dataset-dir", default="distill_datasets/hybrid_teachers__42")
    parser.add_argument("--tasks", type=int, nargs="*", default=list(range(10)))
    parser.add_argument("--save-dir", default="agents/student__hybrid_distill__42")
    parser.add_argument(
        "--student-model-type",
        choices=["simple", "mlp"],
        default="simple",
        help="simple uses repository SimpleAgent; mlp uses a larger distillation-only student defined in this script.",
    )
    parser.add_argument("--hidden-dim", type=int, default=512)
    parser.add_argument("--num-layers", type=int, default=3)
    parser.add_argument("--activation", choices=["relu", "gelu", "tanh"], default="relu")
    parser.add_argument("--layer-norm", default=False, action="store_true")
    parser.add_argument("--steps", type=int, default=20000)
    parser.add_argument("--batch-size", type=int, default=256)
    parser.add_argument("--lr", type=float, default=3e-4)
    parser.add_argument("--weight-decay", type=float, default=0.0)
    parser.add_argument("--temperature", type=float, default=1.0)
    parser.add_argument(
        "--kl-direction",
        choices=["forward", "reverse"],
        default="forward",
        help="forward means KL(teacher || student); reverse means KL(student || teacher).",
    )
    parser.add_argument("--mean-mse-coef", type=float, default=0.0)
    parser.add_argument(
        "--action-mse-coef",
        type=float,
        default=1.0,
        help="Auxiliary MSE on tanh(student_mean) versus saved teacher env actions.",
    )
    parser.add_argument("--max-grad-norm", type=float, default=10.0)
    parser.add_argument("--log-every", type=int, default=200)
    parser.add_argument("--save-every", type=int, default=0)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--torch-deterministic", default=True, action=argparse.BooleanOptionalAction)
    parser.add_argument("--balanced-tasks", default=True, action=argparse.BooleanOptionalAction)
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    return parser.parse_args()


if __name__ == "__main__":
    train(parse_args())
